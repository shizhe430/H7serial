/* 列序(column-major)显示: 32列, 每列4字节(32像素), MSB(bit7=上方) */
void LCD_ShowChinese(u16 x, u16 y, u8 index, u16 color)
{
    u8 col, j, bit;
    const u8 *d = font_chinese_32[index];

    for (col = 0; col < 32; col++) {
        for (j = 0; j < 4; j++) {
            u8 byte = d[col * 4 + j];
            if (byte == 0) continue;
            for (bit = 0; bit < 8; bit++) {
                if (byte & (0x80 >> bit)) {
                    LCD_Fast_DrawPoint(x + col, y + j * 8 + bit, color);
                }
            }
        }
    }
}
